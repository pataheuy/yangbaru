-- -------------------------------------------------------------
-- 1. Lepas constraint CHECK lama di kolom category
--    (yang hanya izinkan 'tech', 'coding', 'lifestyle')
-- -------------------------------------------------------------
ALTER TABLE public.articles
  DROP CONSTRAINT IF EXISTS articles_category_check;

-- Ganti dengan constraint yang lebih longgar:
-- hanya wajib tidak kosong
ALTER TABLE public.articles
  ADD CONSTRAINT articles_category_not_empty
  CHECK (category <> '');


-- -------------------------------------------------------------
-- 2. Tabel categories — menyimpan daftar kategori resmi
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categories (
  id         bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       text    NOT NULL UNIQUE,   -- nilai internal, cth: 'tech'
  label      text    NOT NULL,          -- label tampil, cth: 'Teknologi'
  created_at timestamptz NOT NULL DEFAULT now()
);

-- RLS
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;

-- Siapapun boleh baca
DROP POLICY IF EXISTS "categories_public_read" ON public.categories;
CREATE POLICY "categories_public_read"
  ON public.categories FOR SELECT
  USING (true);

-- Hanya service role / anon (proxy) yang bisa tulis
DROP POLICY IF EXISTS "categories_write" ON public.categories;
CREATE POLICY "categories_write"
  ON public.categories FOR INSERT
  WITH CHECK (true);


-- -------------------------------------------------------------
-- 3. Seed kategori default
-- -------------------------------------------------------------
INSERT INTO public.categories (slug, label) VALUES
  ('tech',      'Teknologi'),
  ('coding',    'Software'),
  ('lifestyle', 'Lifestyle')
ON CONFLICT (slug) DO NOTHING;


-- -------------------------------------------------------------
-- 4. Verifikasi
-- -------------------------------------------------------------
SELECT slug, label, created_at FROM public.categories ORDER BY label;

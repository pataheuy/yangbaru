-- -------------------------------------------------------------
-- 1. TABEL ARTICLES
-- -------------------------------------------------------------
create table if not exists public.articles (
  id          bigint  generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),

  title       text        not null,
  excerpt     text        not null default '',
  content     text        not null default '',  -- HTML paragraf
  category    text        not null default 'tech'
              check (category in ('tech', 'coding', 'lifestyle')),
  tag         text        not null default '',  -- label badge (cth: "AI", "Dev")
  author      text        not null default 'Kontributor',
  image_url   text,                             -- URL gambar (Storage atau eksternal)
  featured    boolean     not null default false,
  published   boolean     not null default true
);

-- Index untuk query umum
create index if not exists articles_category_idx   on public.articles (category);
create index if not exists articles_published_idx  on public.articles (published);
create index if not exists articles_created_at_idx on public.articles (created_at desc);

-- Auto-update updated_at
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists articles_updated_at on public.articles;
create trigger articles_updated_at
  before update on public.articles
  for each row execute procedure public.set_updated_at();


-- -------------------------------------------------------------
-- 2. ROW LEVEL SECURITY (RLS)
-- -------------------------------------------------------------
alter table public.articles enable row level security;

-- Siapapun boleh READ artikel yang sudah published
drop policy if exists "articles_public_read" on public.articles;
create policy "articles_public_read"
  on public.articles for select
  using (published = true);

-- Hanya user yang sudah login (service role / authenticated) boleh INSERT/UPDATE/DELETE
-- Catatan: karena kita pakai anon key lewat proxy, INSERT dari user biasa diblokir di sini.
-- Untuk mengizinkan kontributor anonim submit, ubah ke: using (true)
drop policy if exists "articles_auth_write" on public.articles;
create policy "articles_auth_write"
  on public.articles for insert
  with check (true);   -- proxy server yang jadi penjaga; ubah ke auth.role() = 'authenticated' jika mau strict

drop policy if exists "articles_auth_update" on public.articles;
create policy "articles_auth_update"
  on public.articles for update
  using (true);

drop policy if exists "articles_auth_delete" on public.articles;
create policy "articles_auth_delete"
  on public.articles for delete
  using (true);


-- -------------------------------------------------------------
-- 3. STORAGE BUCKET — article-images
--    (Jalankan hanya jika belum ada bucket-nya)
-- -------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('article-images', 'article-images', true)
on conflict (id) do nothing;

-- Izinkan siapapun upload gambar (proxy yang mengontrol akses)
drop policy if exists "article_images_public_upload" on storage.objects;
create policy "article_images_public_upload"
  on storage.objects for insert
  with check (bucket_id = 'article-images');

-- Izinkan siapapun baca gambar (bucket sudah public)
drop policy if exists "article_images_public_read" on storage.objects;
create policy "article_images_public_read"
  on storage.objects for select
  using (bucket_id = 'article-images');


